import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
import {receiveMinimalText} from '../ui-host/minimal-transport-pair8192.mjs';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..'),here=path.join(root,'.rpg04-work/rpg05-minimal-plan20');
const hash=b=>createHash('sha256').update(b).digest('hex');
const read=async p=>JSON.parse(await fs.readFile(p,'utf8'));
const save=async(p,v)=>fs.writeFile(p,JSON.stringify(v,null,2)+'\n',{flag:'wx'});
if(process.argv[2]!=='execute'||process.argv[3]!=='12')throw Error('ONLY_APPROVED_COMBINATION_12');
const bytes=await fs.readFile(path.join(here,'case-12.json')),c=JSON.parse(bytes);
if(hash(bytes)!==process.argv[4]||c.id!==12)throw Error('CASE_DRIFT');
const authBytes=await fs.readFile(path.join(here,'authorization.json')),auth=JSON.parse(authBytes);
if(hash(authBytes)!==c.authorizationSha256||auth.maxDispatches!==20||auth.priorConsumed!==40)throw Error('AUTH_DRIFT');
const approvalBytes=await fs.readFile(path.join(here,'user-approval-enriched-format.json')),approval=JSON.parse(approvalBytes);
if(hash(approvalBytes)!==c.userApprovalSha256||approval.decision!=='approved')throw Error('USER_APPROVAL_REQUIRED');
for(const f of c.sources)if(hash(await fs.readFile(path.join(root,f.path)))!==f.sha256)throw Error('SOURCE_OR_OUTPUT_DRIFT');
const ledger=(await fs.readdir(here)).filter(n=>/^dispatch-\d+$/.test(n)).sort();
if(JSON.stringify(ledger)!==JSON.stringify([...Array.from({length:11},(_,i)=>'dispatch-'+(i+1)),'dispatch-20'].sort()))throw Error('LEDGER_SEQUENCE');
const recovery=await read(path.join(here,'dispatch-20/RESULT.json'));if(recovery.status!=='passed'||recovery.kind!=='certification_recovery')throw Error('RECOVERY_REQUIRED');
const qResponse=await fetch('http://127.0.0.1:18305/api/models/provider-chat-control?model_id=gpt-5.6-luna&capability=chat_text',{redirect:'error',signal:AbortSignal.timeout(10000)});
if(!qResponse.ok)throw Error('CONTROL_FAILED');
const qualification=await qResponse.json();
if(!qualification.available||qualification.reason_code!=='qualified')throw Error('QUALIFICATION_REQUIRED');
const tokenAuth=await read(path.join(here,'approved-diff-coverage-plan.json')); if(tokenAuth.maxOutputTokens!==8192||!tokenAuth.slots.includes(12))throw Error('TOKEN_AUTH_REQUIRED');
if(tokenAuth.status!=='approved'||hash(await fs.readFile(path.join(here,'dispatch-9/response.txt')))!==tokenAuth.baselineOutputSha256)throw Error('BASELINE_APPROVAL_REQUIRED');
const pair=await read(path.join(here,'batchB-pair.json'));for(const entry of pair.cases)if(hash(await fs.readFile(path.join(here,entry.file)))!==entry.sha256)throw Error('PAIR_DRIFT');
const baselineApproval=await read(path.join(here,'user-approval-B11.json'));
if(baselineApproval.decision!=='approved_as_comparison'||hash(await fs.readFile(path.join(here,'dispatch-11/response.txt')))!==baselineApproval.outputSha256)throw Error('B11_REVIEW_REQUIRED');
const dir=path.join(here,'dispatch-12');await fs.mkdir(dir);
await save(path.join(dir,'reservation.json'),{slot:12,caseSha256:hash(bytes),authorizationSha256:hash(authBytes),at:new Date().toISOString()});
await save(path.join(dir,'qualification.json'),qualification);
const result=await receiveMinimalText(c.payload);
await fs.writeFile(path.join(dir,'response.txt'),result.text,{flag:'wx'});
await fs.writeFile(path.join(dir,'response.sse'),result.raw,{flag:'wx'});
const {text,raw,...meta}=result;
const receipt={...meta,textSha256:hash(text),rawSha256:hash(raw),characters:[...text].length,slot:12,newConsumed:13,newRemaining:7,totalConsumed:53,quality:'pending_user_review',formalUiTurns:0,at:new Date().toISOString()};
await save(path.join(dir,'RESULT.json'),receipt);
console.log(JSON.stringify(receipt));
if(result.status!=='transport_complete')process.exitCode=1;
