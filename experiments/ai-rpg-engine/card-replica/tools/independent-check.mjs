import assert from 'node:assert/strict';
import {readFile,writeFile,mkdir,mkdtemp} from 'node:fs/promises';
import {createHost} from '../server.mjs';
import {hash,loadFrozen,defaults} from '../lib/assembly.mjs';
const root=new URL('../',import.meta.url), out=new URL('../.local/independent-20260917/',import.meta.url);
await mkdir(out,{recursive:true});
const delivery=JSON.parse(await readFile(new URL('resources/DELIVERY.json',root),'utf8'));
const mismatches=[];
for(const item of [...delivery.files,...delivery.build])if(hash(await readFile(new URL(item.path,root)))!==item.sha256)mismatches.push(item.path);
assert.deepEqual(mismatches,[]);
await writeFile(new URL('baseline-DELIVERY.json',out),JSON.stringify(delivery,null,2),{flag:'wx'});
const {prompts,manifest}=loadFrozen();
for(const item of manifest.files)assert.equal(hash(await readFile(new URL('.local/originals/'+item.path,root))),item.sha256);
const captured=[];
const directory=await mkdtemp(new URL('sessions-',out).pathname.replace(/^\/([A-Z]:)/,'$1'));
const raw='\n<details open><summary>虚构验收输出</summary><p>完整保留</p></details>\n';
const host=await createHost({port:0,directory,generate:async x=>{captured.push({messages:x.messages,params:x.params});return raw;}});
const origin='http://127.0.0.1:'+host.port;
const post=async(path,body)=>{const r=await fetch(origin+path,{method:'POST',headers:{origin,'content-type':'application/json'},body:JSON.stringify(body)});const data=await r.json();return {status:r.status,data};};
try {
 const character='【角色设定】\n姓名：独立验收虚构角色\n不含私人草稿';
 const created=await post('/api/sessions',{characterText:character,world:'表世界',params:defaults,mode:'offline',system:'untrusted',provider:'untrusted'});
 assert.equal(created.status,201);
 const id=created.data.id;
 const one=await post('/api/sessions/'+id+'/send',{input:'开始\n  原样',revision:0,requestId:'first',messages:[{role:'system',content:'untrusted'}]});
 assert.equal(one.data.revision,1);
 const two=await post('/api/sessions/'+id+'/send',{input:'继续\n  原样',revision:1,requestId:'second'});
 assert.equal(two.data.revision,2);
 assert.deepEqual(captured[0],{messages:[{role:'system',content:prompts.system},{role:'user',content:character+'\n\n开始\n  原样'}],params:defaults});
 assert.deepEqual(captured[1],{messages:[...captured[0].messages,{role:'assistant',content:raw},{role:'user',content:prompts.prefix+'\n继续\n  原样\n'+prompts.suffix}],params:defaults});
 assert.equal(two.data.turns[0].raw,raw);
 const recovered=await (await fetch(origin+'/api/sessions/'+id)).json();
 assert.equal(recovered.turns.length,2);
 await post('/api/sessions/'+id+'/send',{input:'继续\n  原样',revision:1,requestId:'second'});
 assert.equal(captured.length,2);
 await writeFile(new URL('actual-host-capture.json',out),JSON.stringify(captured,null,2));
 await writeFile(new URL('baseline-results.json',out),JSON.stringify({at:new Date().toISOString(),delivery:27,originals:manifest.files.length,host:'passed',calls:captured.length,evidenceKind:'offline injected generator, no Provider',captureHash:hash(JSON.stringify(captured)),checks:['exact first turn','exact continuation','full literal history','default params passed by host','untrusted system ignored','raw retained','restore without replay','idempotency']},null,2));
 console.log('PASS: 27 delivery hashes, 177 originals, actual HTTP host first/continuation capture, raw history, params, restore/idempotency. Provider dispatches: 0.');
}finally{await new Promise(r=>host.server.close(r));}
