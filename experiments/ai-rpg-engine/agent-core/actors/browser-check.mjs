// Existing Playwright only; isolated data, browser and loopback service.
import {createRequire} from 'node:module';import {mkdir,mkdtemp,writeFile} from 'node:fs/promises';
import {join,resolve} from 'node:path';import {fileURLToPath} from 'node:url';import assert from 'node:assert/strict';
import {startServer} from './server.mjs';
if(!process.env.R6_PLAYWRIGHT_MODULE)throw Error('Set R6_PLAYWRIGHT_MODULE to an existing Playwright directory. Nothing is installed.');
const require=createRequire(join(resolve(process.env.R6_PLAYWRIGHT_MODULE),'package.json')),{chromium}=require('./index.js');
const root=fileURLToPath(new URL('../../.rpg03-work/r6-validation/',import.meta.url));await mkdir(root,{recursive:true});
const dir=await mkdtemp(join(root,'browser-')),app=await startServer({directory:join(dir,'data'),port:0,offlinePreview:true});
let browser;const errors=[],blocked=[],checks=[];
try{
 browser=await chromium.launch({channel:'msedge',headless:true});const context=await browser.newContext({viewport:{width:1440,height:1080}});
 await context.route('**/*',route=>{if(route.request().url().startsWith(app.url))return route.continue();blocked.push(route.request().url());return route.abort();});
 const page=await context.newPage();page.on('pageerror',e=>errors.push(e.message));
 const wait=()=>page.waitForFunction(()=>!document.querySelector('#create').disabled);
 await page.goto(app.url);await page.getByRole('button',{name:'创建独立场景',exact:true}).click();await wait();
 assert.equal(await page.locator('#quantity').innerText(),'5');checks.push('create-and-frozen-opening');
 await page.getByRole('button',{name:'准备服用 2 份',exact:true}).click();
 assert.equal(await page.locator('#quantity').innerText(),'5');
 await page.getByRole('button',{name:'确认服用 2 份',exact:true}).click();await wait();
 assert.equal(await page.locator('#quantity').innerText(),'3');assert.match(await page.locator('#receipt').innerText(),/5 → 3/);checks.push('confirmation-before-once-only-execution');
 await page.getByRole('button',{name:'刚才发生了什么？',exact:true}).click();await wait();
 assert.match(await page.locator('#conversation').innerText(),/看见你服用了两份/);
 await page.getByRole('button',{name:'还剩多少？',exact:true}).click();await wait();
 assert.match(await page.locator('#conversation').innerText(),/没有查阅/);checks.push('witness-observation-is-not-inventory');
 await page.locator('#actor').selectOption('outsider');
 await page.getByRole('button',{name:'刚才发生了什么？',exact:true}).click();await wait();
 assert.match(await page.locator('#conversation').innerText(),/没有这件事/);
 assert.doesNotMatch(await page.locator('#conversation').innerText(),/看见你服用了两份/);checks.push('separate-instance-history-and-no-observation');
 await page.reload();await wait();assert.equal(await page.locator('#quantity').innerText(),'3');checks.push('refresh-without-dispatch');
 await page.locator('#grant').selectOption('inventory');await page.getByRole('button',{name:'创建独立场景',exact:true}).click();await wait();
 await page.getByRole('button',{name:'准备服用 2 份',exact:true}).click();await page.getByRole('button',{name:'确认服用 2 份',exact:true}).click();await wait();
 await page.getByRole('button',{name:'还剩多少？',exact:true}).click();await wait();assert.match(await page.locator('#conversation').innerText(),/还剩3份/);
 checks.push('separate-inventory-grant-native-query');
 await page.getByRole('button',{name:'接下来呢？',exact:true}).click();await wait();
 await page.getByRole('button',{name:'玩家转述：已经赠药',exact:true}).click();await wait();assert.equal(await page.locator('#quantity').innerText(),'3');
 assert.match(await page.locator('#conversation').innerText(),/转述/);checks.push('continuation-and-unconfirmed-claim');
 const id=await page.evaluate(()=>localStorage.getItem('r6-bridge-session'));
 const evidence=await (await fetch(app.url+'api/sessions/'+id+'/evidence')).json();assert.equal(evidence.realCalls,0);
 assert.equal(evidence.world.record.events.length,1);assert.equal(evidence.bridge.actors.witness.observations.length,1);
 await writeFile(join(dir,'evidence.json'),JSON.stringify(evidence,null,2));
 await page.screenshot({path:join(dir,'desktop.png'),fullPage:true});
 await page.setViewportSize({width:390,height:844});await page.reload();await wait();
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 assert.equal(await page.locator('#quantity').innerText(),'3');await page.screenshot({path:join(dir,'mobile.png'),fullPage:true});checks.push('mobile-and-persisted-record');
 const download=await page.locator('#download').getAttribute('href');assert.ok(download.endsWith('/evidence'));
 assert.equal((await fetch(new URL(download,app.url))).status,200);checks.push('download-evidence');
 assert.deepEqual(errors,[]);assert.deepEqual(blocked,[]);
 const result={passed:true,kind:'offline-browser',checks,realCalls:0,costUSD:0,pageErrors:errors,outboundAttempts:blocked,evidenceDirectory:dir};
 await writeFile(join(dir,'result.json'),JSON.stringify(result,null,2));console.log(JSON.stringify(result));
}finally{if(browser)await browser.close();await app.close();}
