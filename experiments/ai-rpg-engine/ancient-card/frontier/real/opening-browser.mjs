import assert from 'node:assert/strict';
import {mkdir,writeFile} from 'node:fs/promises';
import {join,resolve} from 'node:path';
import {createRequire} from 'node:module';
import {preview} from '../ordinary-preview.mjs';
import {offlineNarrator} from '../transport.mjs';
const {chromium}=createRequire(import.meta.url)(process.env.PLAYWRIGHT_MODULE||'playwright');
const dir=resolve('.rpg03-work/ordinary-opening-gemini');
await mkdir(dir,{recursive:true});
const put=(name,x)=>writeFile(join(dir,name),JSON.stringify(x,null,2),{flag:'wx'});
const host=await preview(join(dir,'browser-save'),0,true,async packet=>{await put('browser-request.json',packet);return offlineNarrator(packet);});
let browser;
try{
 browser=await chromium.launch({channel:'msedge',headless:true});
 const page=await browser.newPage();page.setDefaultTimeout(10000);
 await page.goto(host.origin+'/rpg-app/ancient/chat/');
 const f=page.frameLocator('iframe[title="古代人生开局面板"]');
 const next=()=>f.locator('.step.active .nav button[onclick="next()"]').click();
 await f.getByRole('button',{name:'踏入此世'}).click();
 await f.locator('.route-item').filter({hasText:'帝王之路'}).click();await next();
 await f.locator('#empList .acc-head').filter({has:f.locator('h4',{hasText:/^明$/})}).click();
 await f.locator('.emp-row').filter({hasText:'崇祯帝朱由检'}).click();
 for(const [group,text] of [['empMode','穿越成此人'],['empStage','崛起之初'],['empFree','以史为底，允许偏离'],['empSitu','内忧外患']])await f.locator('#'+group).getByText(text,{exact:true}).click();
 await next();await next();
 await f.locator('.add-rel').click();await f.locator('.rel-card select').selectOption({label:'仆从'});
 await f.locator('.rel-card input').first().fill('王承恩');
 await f.getByRole('button',{name:'摇卦问天'}).click();
 const candidates=await f.locator('.talent-row').evaluateAll(rows=>rows.map(row=>Object.fromEntries(['name','desc','grade'].map(k=>[k,row.querySelector('.talent-'+k).textContent]))));
 assert.equal(candidates.length,10);await f.locator('#tr0').click();
 const goal='先分清各地实报与传闻，再议政务';
 const scene='崇祯元年七月十三日清晨，京师文华殿。王承恩把尚未批阅的奏疏放在案头。';
 await f.locator('#cGoal').fill(goal);await next();
 await f.locator('#openScene').getByText('清晨醒来',{exact:true}).click();await f.locator('#openExtra').fill(scene);
 await f.locator('#pvBox').filter({hasText:scene}).waitFor();
 const opening=await f.locator('#pvBox').textContent();
 const selected=candidates[0];for(const k of [goal,scene,selected.name+'('+selected.grade+')','穿越成此人','崛起之初','内忧外患','以史为底，允许偏离','仆从（王承恩）'])assert.ok(opening.includes(k),k);
 await f.locator('#pvBox').screenshot({path:join(dir,'scroll.png')});
 await f.locator('#open-chat').click();const input=page.getByRole('textbox',{name:'对话输入'});await input.waitFor();
 const draft=await input.inputValue();assert.equal(draft,opening);
 const sessionId=new URL(page.url()).searchParams.get('session');
 const api=host.origin+'/rpg-app/ancient/chat/api/sessions/'+sessionId;
 assert.equal((await (await fetch(api)).json()).turns.length,0);
 await put('selection.json',{sessionId,opening,draft,candidates,selected,scene,goal});
 await page.getByRole('button',{name:'发送',exact:true}).click();
 await page.locator('.conversation article .model-output').first().waitFor();
 const s=await (await fetch(api)).json();assert.equal(s.turns[0].input,opening);
 console.log(JSON.stringify({count:candidates.length,selected,length:opening.length,browserSession:sessionId}));
}finally{await browser?.close();await host.close();}
