def parse_chat_audio_input_fixture_response(value: str) -> bool:
    """Validate exact fixture semantics without persisting provider text."""

    def reject_duplicate_keys(pairs: list[tuple[str, object]]) -> dict[str, object]:
        result: dict[str, object] = {}
        for key, item in pairs:
            if key in result:
                raise ValueError("duplicate key")
            result[key] = item
        return result

    try:
        parsed = json.loads(value, object_pairs_hook=reject_duplicate_keys)
    except (json.JSONDecodeError, TypeError, ValueError):
        return False
    if not isinstance(parsed, dict) or set(parsed) != {"count", "color"}:
        return False
    count = parsed.get("count")
    color = parsed.get("color")
    return (
        not isinstance(count, bool)
        and isinstance(count, int)
        and count == CHAT_AUDIO_INPUT_FIXTURE_EXPECTED_COUNT
        and isinstance(color, str)
        and color == CHAT_AUDIO_INPUT_FIXTURE_EXPECTED_COLOR
    )
