def _fixture_bytes() -> bytes:
    content = zlib.decompress(
        base64.b64decode(_CHAT_AUDIO_INPUT_FIXTURE_ZLIB_BASE64, validate=True)
    )
    if hashlib.sha256(content).hexdigest() != CHAT_AUDIO_INPUT_FIXTURE_WAV_SHA256:
        raise RuntimeError("chat audio input fixture digest mismatch")
    if (
        len(content) < 44
        or content[:4] != b"RIFF"
        or content[8:12] != b"WAVE"
        or int.from_bytes(content[4:8], "little") + 8 != len(content)
    ):
        raise RuntimeError("chat audio input fixture is not a complete WAV")
    audio_format, channels, sample_rate, byte_rate, block_align, bits = (
        struct.unpack_from("<HHIIHH", content, 20)
    )
    data_offset = content.find(b"data", 36)
    if data_offset < 0 or data_offset + 8 > len(content):
        raise RuntimeError("chat audio input fixture data chunk is missing")
    data_size = int.from_bytes(content[data_offset + 4 : data_offset + 8], "little")
    frame_count = data_size // block_align if block_align else 0
    if (
        audio_format != 1
        or channels != CHAT_AUDIO_INPUT_FIXTURE_CHANNELS
        or sample_rate != CHAT_AUDIO_INPUT_FIXTURE_SAMPLE_RATE_HZ
        or bits != CHAT_AUDIO_INPUT_FIXTURE_BITS_PER_SAMPLE
        or block_align != channels * (bits // 8)
        or byte_rate != sample_rate * block_align
        or frame_count != CHAT_AUDIO_INPUT_FIXTURE_FRAME_COUNT
        or data_offset + 8 + data_size != len(content)
    ):
        raise RuntimeError("chat audio input fixture format mismatch")
    return content


CHAT_AUDIO_INPUT_FIXTURE_WAV_BYTES = _fixture_bytes()
