import fs from "node:fs/promises";
import path from "node:path";
import process from "node:process";

const ARRAY_MARKER = "const rawCatalogModels: RawCatalogModel[] = ";
const ROUTE_ARRAY_MARKER =
  "const rawRouteVariantModels: RawCatalogModel[] = ";
const UNCERTAIN_MARKER =
  "const uncertainCatalogModelIds = new Set<string>(";
const CURRENT_TIME_MARKER = "const CURRENT_TIME_SECONDS";
const ROUTE_VARIANT_SUFFIX = ":batch";
const SPECIALIZED_CATALOG_MODEL_IDS = new Set([
  "x-ai/grok-imagine-image-2.0",
]);

function argument(name) {
  const index = process.argv.indexOf(name);
  return index >= 0 ? process.argv[index + 1] : "";
}

async function jsonFile(name) {
  const value = argument(name);
  if (!value) throw new Error(`${name} is required`);
  return JSON.parse(await fs.readFile(path.resolve(value), "utf8"));
}

function parseArrayBetween(source, startMarker, endMarker) {
  const start = source.indexOf(startMarker);
  const end = source.indexOf(endMarker, start + startMarker.length);
  if (start < 0 || end < 0) {
    throw new Error(`models.ts block not found: ${startMarker}`);
  }
  return JSON.parse(
    source
      .slice(start + startMarker.length, end)
      .replace(/;\s*$/, ""),
  );
}

function parseUncertainIds(source) {
  const start = source.indexOf(UNCERTAIN_MARKER);
  const end = source.indexOf(CURRENT_TIME_MARKER, start);
  if (start < 0 || end < 0) {
    throw new Error("uncertain catalog marker not found");
  }
  const ids = JSON.parse(
    source
      .slice(start + UNCERTAIN_MARKER.length, end)
      .replace(/\);\s*$/, ""),
  );
  if (!Array.isArray(ids) || ids.some((value) => typeof value !== "string")) {
    throw new Error("uncertain catalog IDs must be a string array");
  }
  return ids;
}

function modalities(model, key) {
  const value = model?.architecture?.[key] ?? model?.[key];
  return Array.isArray(value) ? value.map(String).sort() : [];
}

function parseExpirationDate(value) {
  if (value == null || value === "") return null;
  if (typeof value === "number" && Number.isFinite(value)) return value;
  const parsed = Date.parse(String(value));
  return Number.isFinite(parsed) ? Math.floor(parsed / 1000) : null;
}

function pricePerMillion(value) {
  const parsed = Number(value);
  return Number.isFinite(parsed) ? parsed * 1_000_000 : 0;
}

function normalizedMetadata(model) {
  return {
    canonical_slug: String(model.canonical_slug || model.id),
    name: String(model.name || model.id),
    raw_description: String(model.description ?? model.raw_description ?? ""),
    context_length: Math.max(0, Number(model.context_length) || 0),
    pricing: {
      input:
        model.pricing?.input ?? pricePerMillion(model.pricing?.prompt),
      output:
        model.pricing?.output ?? pricePerMillion(model.pricing?.completion),
    },
    input_modalities: modalities(model, "input_modalities"),
    output_modalities: modalities(model, "output_modalities"),
    tokenizer: String(
      model.architecture?.tokenizer ?? model.tokenizer ?? "Other",
    ),
    supported_parameters: Array.isArray(model.supported_parameters)
      ? model.supported_parameters.map(String).sort()
      : [],
    created: Math.max(0, Number(model.created) || 0),
    expiration_date: parseExpirationDate(model.expiration_date),
  };
}

function metadataDrift(liveModel, storedModel) {
  const live = normalizedMetadata(liveModel);
  const stored = normalizedMetadata(storedModel);
  return Object.keys(live).filter(
    (field) => JSON.stringify(live[field]) !== JSON.stringify(stored[field]),
  );
}

function count(models, key, value) {
  return models.filter((model) => modalities(model, key).includes(value)).length;
}

async function main() {
  const [catalog, imageCatalog, videoCatalog, source] = await Promise.all([
    jsonFile("--catalog"),
    jsonFile("--image-models"),
    jsonFile("--video-models"),
    fs.readFile(path.resolve("client/src/data/models.ts"), "utf8"),
  ]);
  const allLive = Array.isArray(catalog.data) ? catalog.data : [];
  const live = allLive.filter(
    (model) => !String(model.id).endsWith(ROUTE_VARIANT_SUFFIX),
  );
  const liveRoutes = allLive.filter((model) =>
    String(model.id).endsWith(ROUTE_VARIANT_SUFFIX),
  );
  const images = Array.isArray(imageCatalog.data) ? imageCatalog.data : [];
  const videos = Array.isArray(videoCatalog.data) ? videoCatalog.data : [];
  const snapshot = parseArrayBetween(
    source,
    ARRAY_MARKER,
    ROUTE_ARRAY_MARKER,
  );
  const routeVariants = parseArrayBetween(
    source,
    ROUTE_ARRAY_MARKER,
    "// Generated by scripts/update-openrouter-models.mjs.",
  );
  const uncertainIds = parseUncertainIds(source);
  const snapshotById = new Map(snapshot.map((model) => [model.id, model]));
  const routeById = new Map(routeVariants.map((model) => [model.id, model]));
  const liveIds = new Set(live.map((model) => model.id));
  const liveRouteIds = new Set(liveRoutes.map((model) => model.id));
  const nowSeconds = Math.floor(Date.now() / 1000);
  const expiredIds = snapshot
    .filter(
      (model) =>
        typeof model.expiration_date === "number" &&
        model.expiration_date <= nowSeconds,
    )
    .map((model) => model.id)
    .sort();
  const expiredIdSet = new Set(expiredIds);
  const expectedUncertainIds = snapshot
    .filter(
      (model) => !liveIds.has(model.id) && !expiredIdSet.has(model.id),
    )
    .map((model) => model.id)
    .sort();
  const recordedUncertainIds = [...new Set(uncertainIds)].sort();
  const uncertainStatusMismatches = [
    ...expectedUncertainIds.filter(
      (modelId) => !recordedUncertainIds.includes(modelId),
    ),
    ...recordedUncertainIds.filter(
      (modelId) =>
        liveIds.has(modelId) ||
        expiredIdSet.has(modelId) ||
        !snapshotById.has(modelId),
    ),
  ];
  const missingLiveModels = live
    .filter((model) => !snapshotById.has(model.id))
    .map((model) => model.id);
  const missingRouteVariants = liveRoutes
    .filter((model) => !routeById.has(model.id))
    .map((model) => model.id);
  const staleRouteVariants = routeVariants
    .filter((model) => !liveRouteIds.has(model.id))
    .map((model) => model.id);
  const metadataMismatches = live
    .filter(
      (model) =>
        snapshotById.has(model.id) &&
        !SPECIALIZED_CATALOG_MODEL_IDS.has(model.id),
    )
    .map((model) => ({
      id: model.id,
      fields: metadataDrift(model, snapshotById.get(model.id)),
    }))
    .filter((item) => item.fields.length > 0);
  const routeMetadataMismatches = liveRoutes
    .filter((model) => routeById.has(model.id))
    .map((model) => ({
      id: model.id,
      fields: metadataDrift(model, routeById.get(model.id)),
    }))
    .filter((item) => item.fields.length > 0);
  const imageIds = new Set(images.map((model) => model.id));
  const videoIds = new Set(videos.map((model) => model.id));
  const imageApiMissingFromSnapshot = images
    .filter((model) => !snapshotById.has(model.id))
    .map((model) => model.id);
  const videoApiMissingFromSnapshot = videos
    .filter((model) => !snapshotById.has(model.id))
    .map((model) => model.id);
  const generalImageOutputWithoutDedicatedApi = live
    .filter(
      (model) =>
        modalities(model, "output_modalities").includes("image") &&
        !imageIds.has(model.id),
    )
    .map((model) => model.id);
  const generalVideoOutputWithoutDedicatedApi = live
    .filter(
      (model) =>
        modalities(model, "output_modalities").includes("video") &&
        !videoIds.has(model.id),
    )
    .map((model) => model.id);

  const report = {
    generated_at: new Date().toISOString(),
    snapshot_total: snapshot.length,
    route_variant_total: routeVariants.length,
    route_variants_counted_in_snapshot: false,
    catalog_total: allLive.length,
    live_snapshot_total: live.length,
    catalog_lifecycle: {
      live: live.length,
      uncertain: recordedUncertainIds.length,
      expired: expiredIds.length,
    },
    live_modalities: {
      input: {
        text: count(live, "input_modalities", "text"),
        image: count(live, "input_modalities", "image"),
        audio: count(live, "input_modalities", "audio"),
        video: count(live, "input_modalities", "video"),
        file: count(live, "input_modalities", "file"),
      },
      output: {
        text: count(live, "output_modalities", "text"),
        image: count(live, "output_modalities", "image"),
        audio: count(live, "output_modalities", "audio"),
        speech: count(live, "output_modalities", "speech"),
        transcription: count(live, "output_modalities", "transcription"),
        video: count(live, "output_modalities", "video"),
      },
    },
    dedicated_catalogs: {
      image_generation: images.length,
      video_generation: videos.length,
    },
    missing_live_models: missingLiveModels,
    metadata_mismatches: metadataMismatches,
    missing_route_variants: missingRouteVariants,
    stale_route_variants: staleRouteVariants,
    route_metadata_mismatches: routeMetadataMismatches,
    image_api_missing_from_snapshot: imageApiMissingFromSnapshot,
    video_api_missing_from_snapshot: videoApiMissingFromSnapshot,
    general_image_output_without_dedicated_api:
      generalImageOutputWithoutDedicatedApi,
    general_video_output_without_dedicated_api:
      generalVideoOutputWithoutDedicatedApi,
    uncertain_status_mismatches: uncertainStatusMismatches,
    expired_model_ids: expiredIds,
    specialized_metadata_exceptions: [
      "x-ai/grok-imagine-image-2.0 uses the dedicated image catalog contract",
    ],
  };
  process.stdout.write(`${JSON.stringify(report, null, 2)}\n`);
  if (
    missingLiveModels.length ||
    metadataMismatches.length ||
    missingRouteVariants.length ||
    staleRouteVariants.length ||
    routeMetadataMismatches.length ||
    imageApiMissingFromSnapshot.length ||
    videoApiMissingFromSnapshot.length ||
    generalVideoOutputWithoutDedicatedApi.length ||
    uncertainStatusMismatches.length
  ) {
    process.exitCode = 1;
  }
}

await main();
