import fs from "node:fs/promises";
import path from "node:path";

const REPORT_PATH = path.resolve(
  process.argv[2] || "docs/multimodal-readiness.json",
);
const MODELS_PATH = path.resolve("client/src/data/models.ts");
const VIDEO_CATALOG_PATH = path.resolve(
  "server/multimodal/video_catalog.py",
);

const ARRAY_MARKER = "const rawCatalogModels: RawCatalogModel[] = ";
const HISTORY_BLOCK_MARKER = "// Generated by scripts/update-openrouter-models.mjs.";
const HISTORY_MARKER = "const historicalCatalogModelIds = new Set<string>(";
const CURRENT_TIME_MARKER = "const CURRENT_TIME_SECONDS";

function parseSnapshot(source) {
  const start = source.indexOf(ARRAY_MARKER);
  const historyBlockStart = source.indexOf(HISTORY_BLOCK_MARKER, start);
  const historyStart = source.indexOf(HISTORY_MARKER, start);
  const currentTimeStart = source.indexOf(CURRENT_TIME_MARKER, start);
  const end =
    historyBlockStart >= 0
      ? historyBlockStart
      : historyStart >= 0
        ? historyStart
        : currentTimeStart;
  if (start < 0 || end < 0) throw new Error("models.ts snapshot not found");
  return JSON.parse(
    source.slice(start + ARRAY_MARKER.length, end).replace(/;\s*$/, ""),
  );
}

function parseHistoricalIds(source) {
  const start = source.indexOf(HISTORY_MARKER);
  const end = source.indexOf(CURRENT_TIME_MARKER, start);
  if (start < 0 || end < 0) {
    throw new Error("historical catalog marker not found");
  }
  return JSON.parse(
    source.slice(start + HISTORY_MARKER.length, end).replace(/\);\s*$/, ""),
  );
}

function parseVerifiedVideoIds(source) {
  const start = source.indexOf("VERIFIED_VIDEO_GENERATION_MODELS = frozenset(");
  const end = source.indexOf("HIGH_COST_VIDEO_VERIFICATION_MODELS", start);
  if (start < 0 || end < 0) {
    throw new Error("verified video registry not found");
  }
  return [...source.slice(start, end).matchAll(/"([^"]+)"/g)]
    .map((match) => match[1])
    .sort();
}

function assertEqual(actual, expected, label) {
  if (JSON.stringify(actual) !== JSON.stringify(expected)) {
    throw new Error(
      `${label} mismatch: expected ${JSON.stringify(expected)}, got ${JSON.stringify(actual)}`,
    );
  }
}

function assertReasons(entries, label) {
  for (const entry of entries) {
    if (
      ["planned", "disabled"].includes(entry.status) &&
      !(typeof entry.status_reason === "string" && entry.status_reason.trim())
    ) {
      throw new Error(
        `${label} ${entry.model_id || entry.capability || "unknown"} lacks status_reason`,
      );
    }
  }
}

async function main() {
  const [reportSource, modelsSource, videoSource] = await Promise.all([
    fs.readFile(REPORT_PATH, "utf8"),
    fs.readFile(MODELS_PATH, "utf8"),
    fs.readFile(VIDEO_CATALOG_PATH, "utf8"),
  ]);
  const report = JSON.parse(reportSource);
  const snapshot = parseSnapshot(modelsSource);
  const historicalIds = new Set(parseHistoricalIds(modelsSource));
  const nowSeconds = Math.floor(Date.now() / 1000);
  const expiredIds = new Set(
    snapshot
      .filter(
        (model) =>
          typeof model.expiration_date === "number" &&
          model.expiration_date <= nowSeconds,
      )
      .map((model) => model.id),
  );
  const historicalCount = [...historicalIds].filter(
    (modelId) => !expiredIds.has(modelId),
  ).length;
  const liveCount = snapshot.filter(
    (model) => !historicalIds.has(model.id) && !expiredIds.has(model.id),
  ).length;
  const onsiteCount = liveCount + historicalCount;

  assertEqual(report.catalog.snapshot_total, snapshot.length, "snapshot_total");
  assertEqual(report.catalog.live, liveCount, "live lifecycle count");
  assertEqual(report.catalog.historical, historicalCount, "historical count");
  assertEqual(report.catalog.expired, expiredIds.size, "expired count");
  assertEqual(report.catalog.onsite_openrouter, onsiteCount, "onsite count");
  assertEqual(
    report.catalog.adaptation_denominator,
    onsiteCount,
    "adaptation denominator",
  );
  if (
    report.catalog.historical_included_in_onsite !== true ||
    report.catalog.expired_excluded_from_onsite !== true
  ) {
    throw new Error("catalog metric policy must include retained history and exclude expired models");
  }

  assertReasons(report.operation_readiness || [], "operation readiness");
  assertReasons(report.deferred_capabilities || [], "deferred capability");

  const registryIds = parseVerifiedVideoIds(videoSource);
  const reportVideoIds = (report.video_generation?.verified || [])
    .map((entry) => entry.model_id)
    .sort();
  assertEqual(reportVideoIds, registryIds, "verified video evidence registry");
  assertEqual(
    report.video_generation.dedicated_profiles,
    registryIds.length,
    "dedicated video profile count",
  );
  assertEqual(
    report.video_generation.verification_required || [],
    [],
    "pending video verification list",
  );
  for (const entry of report.video_generation.verified || []) {
    if (
      !entry.verified_at ||
      !Array.isArray(entry.evidence) ||
      !entry.evidence.includes("manual_submission") ||
      !entry.evidence.includes("playback") ||
      !entry.evidence.includes("download")
    ) {
      throw new Error(`${entry.model_id} lacks complete manual video evidence`);
    }
  }

  process.stdout.write(
    `${JSON.stringify({
      status: "ok",
      report: path.relative(process.cwd(), REPORT_PATH),
      catalog: report.catalog,
      verified_video_models: registryIds.length,
      explained_non_ready_operations: [
        ...(report.operation_readiness || []),
        ...(report.deferred_capabilities || []),
      ].filter((entry) => ["planned", "disabled"].includes(entry.status)).length,
    }, null, 2)}\n`,
  );
}

await main();
